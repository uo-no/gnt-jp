const ledger = JSON.parse(fs.readFileSync(LEDGER, 'utf8'));

let approvedCount = 0;
let deferredCount = 0;
let unchanged = 0;

ledger.candidates = ledger.candidates.map(c => {
  if (c.strong !== 'G435') return c;

  if (APPROVED.has(c.ref)) {
    approvedCount++;
    return {
      ...c,
      status: '修正承認',
      currentJapanese: c.japanese_before,   // 現在値（「男」）は変更しない
      proposedJapanese: '人',
      decisionReason: `JA1955テキストで「人」「人たち」「人々」等を直接確認。${c.decisionReason || ''}`.trim(),
      reviewedAt: REVIEWED_AT,
    };
  }

  if (DEFERRED[c.ref]) {
    deferredCount++;
    return {
      ...c,
      status: '判断保留',
      currentJapanese: c.japanese_before,
      proposedJapanese: c.japanese_proposed,
      decisionReason: DEFERRED[c.ref],
      reviewedAt: REVIEWED_AT,
    };
  }

  unchanged++;
  return c;
});

// ステータス集計を再計算
const statusCounts = {};
for (const c of ledger.candidates) {
  statusCounts[c.status] = (statusCounts[c.status] || 0) + 1;
}
ledger.stats.statusCounts = statusCounts;
ledger._meta.lastUpdated = REVIEWED_AT;
ledger._meta.g435ReviewCompleted = REVIEWED_AT;

fs.writeFileSync(LEDGER, JSON.stringify(ledger, null, 2), 'utf8');
console.log('G435決定適用完了:');
